"""Generate procedural textures and embed them as data URIs in assets/textures.js.

Textures are embedded (not loaded as image files) so index.html works from file://:
Chrome refuses to upload file:// images into WebGL.
Usage: python3 tools/build_textures.py
"""
import base64
import io
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def checker(size=256, cells=8, a=(235, 235, 235), b=(90, 90, 90)):
    img = Image.new("RGB", (size, size))
    px = img.load()
    step = size // cells
    for y in range(size):
        for x in range(size):
            px[x, y] = a if ((x // step) + (y // step)) % 2 == 0 else b
    return img


def gravel(size=512, seed=7):
    """Light limestone gravel like the site in the photos: multi-scale noise plus scattered stones."""
    import numpy as np
    rng = np.random.default_rng(seed)
    img = np.zeros((size, size))
    for cells, amp in [(8, 0.35), (32, 0.3), (128, 0.25), (512, 0.1)]:
        noise = rng.random((cells, cells))
        # tile-safe upscale: repeat, so the texture wraps without seams
        img += amp * np.kron(noise, np.ones((size // cells, size // cells)))
    for _ in range(900):                     # small stones
        x, y, r = rng.integers(0, size), rng.integers(0, size), rng.integers(2, 6)
        yy, xx = np.ogrid[-r:r + 1, -r:r + 1]
        mask = xx * xx + yy * yy <= r * r
        ys, xs = (np.arange(y - r, y + r + 1) % size)[:, None], (np.arange(x - r, x + r + 1) % size)[None, :]
        img[ys, xs] = np.where(mask, img[ys, xs] * 0.6 + rng.uniform(0.3, 0.9) * 0.4, img[ys, xs])
    img = (img - img.min()) / (img.max() - img.min())
    base = np.array([200, 196, 186]) / 255.0
    rgb = (0.78 + 0.22 * img)[..., None] * base
    return Image.fromarray((np.clip(rgb, 0, 1) * 255).astype("uint8"))


def facade(size=256):
    """White building facade with regular tinted glass windows."""
    img = Image.new("RGB", (size, size), (235, 238, 240))
    px = img.load()
    cell = size // 4
    for r in range(4):
        for c in range(4):
            x0 = c * cell + 10
            x1 = (c + 1) * cell - 10
            y0 = r * cell + 14
            y1 = (r + 1) * cell - 14
            for y in range(y0, y1):
                for x in range(x0, x1):
                    if x == x0 or x == x1 - 1 or y == y0 or y == y1 - 1 or x == (x0 + x1) // 2:
                        px[x, y] = (80, 85, 92)
                    else:
                        px[x, y] = (70, 95, 120)
    return img


def probe_half(size=64):
    """Alpha probe texture: left half opaque white, right half fully transparent."""
    img = Image.new("RGBA", (size, size), (255, 255, 255, 255))
    px = img.load()
    half = size // 2
    for y in range(size):
        for x in range(half, size):
            px[x, y] = (255, 255, 255, 0)
    return img


TEXTURES = {
    "checker": checker,
    "gravel": gravel,
    "facade": facade,
    "probe_half": probe_half,
}


def to_data_uri(img):
    buf = io.BytesIO()
    fmt = "PNG"
    img.save(buf, format=fmt, optimize=True)
    return "data:image/png;base64," + base64.b64encode(buf.getvalue()).decode("ascii")


def main():
    out = os.path.join(ROOT, "assets", "textures.js")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ["// GENERATED by tools/build_textures.py - do not edit or read.",
             "window.TEXTURES = window.TEXTURES || {};"]
    for name, make in TEXTURES.items():
        img = make()
        w, h = img.size
        if w & (w - 1) or h & (h - 1):
            print(f"FAIL {name}: size {w}x{h} is not a power of two (WebGL 1 needs POT for REPEAT/mipmaps)")
            sys.exit(1)
        lines.append(f'window.TEXTURES["{name}"] = "{to_data_uri(img)}";')
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"TEXTURES OK: {len(TEXTURES)} -> assets/textures.js")


if __name__ == "__main__":
    main()
